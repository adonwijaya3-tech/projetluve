-- LuVenXe Store starter schema. Run in Supabase SQL Editor.
-- Never place SUPABASE_SERVICE_ROLE_KEY in browser HTML/JavaScript.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'member' check (role in ('member', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Lainnya',
  description text not null default '',
  price bigint not null check (price > 0),
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_methods (
  id text primary key,
  name text not null,
  fee bigint not null default 0 check (fee >= 0),
  instructions text not null default '',
  qris_image_url text,
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  product_id bigint not null references public.products(id) on delete restrict,
  product_name text not null,
  roblox_username text not null,
  whatsapp text not null,
  note text not null default '',
  payment_method_id text not null references public.payment_methods(id) on delete restrict,
  payment_method_name text not null,
  subtotal bigint not null check (subtotal > 0),
  fee bigint not null default 0 check (fee >= 0),
  total bigint not null check (total > 0),
  status text not null default 'pending' check (status in ('pending','paid','processing','success','rejected','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  sender_role text not null check (sender_role in ('member','admin')),
  message text not null check (char_length(message) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists orders_user_id_created_at_idx on public.orders(user_id, created_at desc);
create index if not exists orders_status_created_at_idx on public.orders(status, created_at desc);
create index if not exists products_active_category_idx on public.products(active, category);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.payment_methods enable row level security;
alter table public.orders enable row level security;
alter table public.store_settings enable row level security;
alter table public.chat_messages enable row level security;

-- Public catalog only exposes active products and active payment methods.
create policy "Public can read active products" on public.products
  for select using (active = true);
create policy "Public can read active payment methods" on public.payment_methods
  for select using (active = true);

-- A signed-in user can read only their own profile and orders.
create policy "Users can read own profile" on public.profiles
  for select to authenticated using (auth.uid() = id);
create policy "Users can update own display name" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id and role = 'member');
create policy "Users can read own orders" on public.orders
  for select to authenticated using (auth.uid() = user_id);
create policy "Users can read own chat" on public.chat_messages
  for select to authenticated using (auth.uid() = user_id);
create policy "Users can send own chat messages" on public.chat_messages
  for insert to authenticated with check (auth.uid() = user_id and sender_role = 'member');

-- Intentionally no browser INSERT/UPDATE policies for orders, products, payments,
-- or store settings. Sensitive writes must go through validated server functions.
-- Admin access to these writes is also expected to go through authenticated functions.

